#!/usr/bin/env python3
"""Rebuild config/common_words.txt (PALENA_PSEUDONYMIZER_COMMON_WORDS_FILE).

Top-N English + Russian words by frequency (wordfreq), lower-case, minus names (so a lone "Ivan",
"Коля", "Petrov", "Baker" is still masked): US-census first names + top surnames (`names` package)
and Russian first names / surname-suffix words.

  uv run --with wordfreq --with names python scripts/build_common_words.py [N=25000]
"""
