RU_SURNAME_SUFFIX = re.compile(r"(ов|ова|ово|ев|ева|ёв|ёва|ин|ина|ын|ына|ский|ская|цкий|цкая|енко|юк|ук|ко|ич|ович|евич)$")
RU_SURNAME_STEMS_OK = set()  # words ending in those suffixes that are NOT surnames are simply left unmasked-excluded (fail towards masking)


# dev / agent vocabulary that general-language frequency lists miss
EXTRA = """codebase repo repos repository readme changelog backend frontend middleware endpoint endpoints
workspace namespace config configs docstring refactor refactoring dockerfile makefile webhook webhooks
tooling toolchain monorepo submodule onboarding stakeholder stakeholders maintainer maintainers
""".split()


def load_names() -> set[str]:
    d = os.path.dirname(names.__file__)
    out = set()
    for f in ("dist.male.first", "dist.female.first"):
        for line in open(os.path.join(d, f)):
            out.add(line.split()[0].lower())
    for i, line in enumerate(open(os.path.join(d, "dist.all.last"))):
        if i >= SURNAMES_TOP:
            break
        out.add(line.split()[0].lower())
    return out


def main() -> None:
    skip = load_names() | set(RU_FIRST)
    words = []
    for lang in ("en", "ru"):
        for w in wordfreq.top_n_list(lang, N):
            w = w.lower()
            if not re.fullmatch(r"[a-zа-яё]{3,}", w):
                continue  # single word, letters only; 1-2 letter hits are rejected elsewhere anyway
            if w in skip:
                continue
            if lang == "ru" and RU_SURNAME_SUFFIX.search(w):
                continue
            words.append(w)
    words = sorted(set(words) | (set(EXTRA) - skip))
    with open(OUT, "w") as f:
        f.write("# Common dictionary words (top %d en + ru by frequency, lower-case) minus first names/surnames.\n"
                "# NER-derived single-word PERSON/ORGANIZATION hits on these are dropped (\"Client\", \"Contact\", \"Billing\").\n"
                "# Generated by scripts/build_common_words.py; PALENA_PSEUDONYMIZER_COMMON_WORDS_FILE.\n" % N)
        f.write("\n".join(words) + "\n")
    print(len(words), "words ->", OUT)


main()
